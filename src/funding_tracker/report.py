"""Write the run summary (reports/summary.md) and refresh the numbers in the README."""
from __future__ import annotations

import re
from datetime import date
from pathlib import Path

import pandas as pd

from .config import AMOUNT_TOLERANCE, ROOT, SOURCE_LABELS, SOURCES
from .reconcile import SOURCE_RULES

README_START, README_END = "<!-- stats:start -->", "<!-- stats:end -->"

REASONS = {
    "excluded_no_funding_verb": "Headline is not about raising money",
    "excluded_not_closed": "Round not closed yet (talks, plans, 'to raise')",
    "excluded_digest": "Round-up of several companies",
    "excluded_investor_fund": "An investor raising a fund, not a startup round",
    "excluded_not_funding": "Verb used in another sense ('raises prices', ESOP buyback)",
    "excluded_public_market": "IPO, anchor round, rights issue or other public-market deal",
    "excluded_no_company": "Company name could not be read",
    "excluded_secondary": "Pure secondary sale",
    "excluded_intra_group": "Parent funding its own subsidiary",
    "excluded_before_window": "Dated before the tracking window",
    "excluded_not_india": "Agency story about a round outside India",
}


def _table(frame: pd.DataFrame) -> str:
    """A small markdown table (avoids needing the optional 'tabulate' package)."""
    header = "| " + " | ".join(str(c) for c in frame.columns) + " |"
    rule = "| " + " | ".join("---" if frame[c].dtype == object else "---:" for c in frame.columns) + " |"
    rows = ["| " + " | ".join(str(v) for v in row) + " |" for row in frame.itertuples(index=False)]
    return "\n".join([header, rule, *rows])


def headline(tables: dict[str, pd.DataFrame]) -> dict[str, object]:
    """The numbers quoted in the README and on the dashboard."""
    rounds, records, merge_log = tables["rounds"], tables["records"], tables["merge_log"]
    matched = int((records["round_id"] != "").sum())
    amounts = rounds["amount_usd_mn"]
    days = pd.to_datetime(rounds["announced_date"])
    checks = tables["checks_summary"].set_index("check_id")["rounds_flagged"]
    return {
        "rounds": len(rounds),
        "first_day": days.min().date(), "last_day": days.max().date(),
        "disclosed_rounds": int(amounts.notna().sum()),
        "funding_usd_bn": float(amounts.sum()) / 1000, "median_usd_mn": float(amounts.median()),
        "reports_matched": matched, "duplicates_merged": matched - len(rounds),
        "variant_merges": int((merge_log["match_basis"] != "identical name").sum()),
        "fuzzy_merges": int(merge_log["match_basis"].str.contains("fuzzy").sum()),
        "multi_source": int((rounds["source_count"] >= 2).sum()),
        "amount_disagreements": int(checks.get("C15", 0)), "scale_mismatches": int(checks.get("C14", 0)),
        "checks": len(checks), "flags": len(tables["exceptions"]),
        "unmatched_headlines": len(tables["unmatched_headlines"]),
    }


def stats_block(tables: dict[str, pd.DataFrame]) -> str:
    """The block of headline numbers that is kept up to date inside README.md."""
    h = headline(tables)
    lines = [
        f"_Numbers below are rewritten by every run. Last run: {date.today():%d %B %Y}._",
        "",
        "| | |",
        "| --- | ---: |",
        f"| Funding rounds tracked | **{h['rounds']:,}** |",
        f"| Period covered | {h['first_day']:%d %b %Y} to {h['last_day']:%d %b %Y} |",
        f"| Source reports matched to a round | {h['reports_matched']:,} |",
        f"| Duplicate reports merged | {h['duplicates_merged']:,} |",
        f"| ...of which the company name differed between reports | {h['variant_merges']:,} |",
        f"| Rounds confirmed by two or more sources | {h['multi_source']:,} ({h['multi_source'] / h['rounds']:.0%}) |",
        f"| Disclosed funding | USD {h['funding_usd_bn']:.2f} bn across {h['disclosed_rounds']:,} rounds |",
        f"| Median disclosed round | USD {h['median_usd_mn']:.2f} mn |",
        f"| Automated checks | {h['checks']} |",
        f"| Rounds where sources disagree on the amount by more than {AMOUNT_TOLERANCE:.0%} | {h['amount_disagreements']:,} |",
        f"| Rounds with a lakh/crore or million/billion mismatch | {h['scale_mismatches']:,} |",
        f"| Funding headlines not yet matched to a round (review list) | {h['unmatched_headlines']:,} |",
    ]
    return "\n".join(lines)


def write_summary(tables: dict[str, pd.DataFrame], path: Path) -> None:
    rounds, records = tables["rounds"], tables["records"]
    parts = [f"# Tracker summary\n\nGenerated by `python -m funding_tracker build`. Do not edit by hand.\n",
             "## Headline numbers\n", stats_block(tables), ""]

    by_source = pd.DataFrame({
        "Source": [SOURCE_LABELS[s] for s in SOURCES],
        "Candidates read": [int((records["source"] == s).sum()) for s in SOURCES],
        "Usable reports": [int(((records["source"] == s) & records["status"].isin(["ok", "confirm_only"])).sum())
                           for s in SOURCES],
        "Matched to a round": [int(((records["source"] == s) & (records["round_id"] != "")).sum()) for s in SOURCES],
    })
    parts += ["## Reports by source\n", _table(by_source), ""]

    left_out = records[~records["status"].isin(["ok", "confirm_only"])].groupby(
        ["status", "source"]).size().unstack(fill_value=0)
    left_out = left_out.reindex(columns=list(SOURCES), fill_value=0)
    left_out.insert(0, "Reason", [REASONS.get(status, status) for status in left_out.index])
    left_out = left_out.rename(columns=SOURCE_LABELS).sort_values("Reason").sort_values(
        list(SOURCE_LABELS.values()), ascending=False, kind="stable")
    parts += ["## Why candidates were left out\n", _table(left_out), ""]

    basis = tables["merge_log"]["match_basis"].value_counts().sort_index().sort_values(
        ascending=False, kind="stable").rename_axis("How the match was made")
    parts += ["## How duplicate reports were recognised\n", _table(basis.reset_index(name="Reports merged")), ""]

    checks = tables["checks_summary"][["check_id", "category", "check", "severity", "rounds_flagged"]].copy()
    checks["share"] = (tables["checks_summary"]["share_flagged"] * 100).round(1).astype(str) + "%"
    checks.columns = ["ID", "Category", "Check", "Severity", "Rounds flagged", "Share"]
    parts += ["## Checks\n", _table(checks), ""]

    coverage = tables["coverage"]
    if not coverage.empty:
        short = int((coverage["difference"] < 0).sum())
        parts += ["## Coverage against Entrackr's weekly reports\n",
                  f"{len(coverage)} weekly reports compared. The tracker holds as many rounds as Entrackr counted, or "
                  f"more, in {len(coverage) - short} of them; in {short} weeks it holds fewer. Median difference: "
                  f"{coverage['difference'].median():+.0f} rounds a week.\n"]

    for column, title in (("stage", "stage"), ("sector", "sector"), ("city", "city")):
        cut = rounds.groupby(column)["amount_usd_mn"].agg(Rounds="size", total="sum")
        cut["USD mn"] = cut.pop("total").round(1)
        cut = cut.rename_axis(title.capitalize()).reset_index()
        cut = cut.sort_values(["Rounds", title.capitalize()], ascending=[False, True]).head(12)    # ties: by name
        parts += [f"## Rounds by {title} (top {len(cut)})\n", _table(cut), ""]

    path.write_text("\n".join(parts), encoding="utf-8")
    update_readme(stats_block(tables))
    write_rules_doc()


def update_readme(block: str, readme: Path = ROOT / "README.md") -> bool:
    """Replace the text between the stats markers in README.md. Returns False if there are no markers."""
    if not readme.exists():
        return False
    text = readme.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(README_START) + r".*?" + re.escape(README_END), re.S)
    if not pattern.search(text):
        return False
    readme.write_text(pattern.sub(lambda _: f"{README_START}\n{block}\n{README_END}", text), encoding="utf-8")
    return True


RULES_INTRO = """# Source of truth

When two sources describe the same round differently, the tracker does not keep whichever report it
happened to read first. Every field has one rule, written below. The rule decides what goes into
`data/processed/rounds.csv`. The disagreement is still flagged by the checks, with each source's own
figure listed, so a person can look at it.
"""

RULES_OUTRO = """## A worked example

Three reports of one round (names are made up):

| Source | Company as written | Published | Amount | Stage |
| --- | --- | --- | --- | --- |
| Entrackr (article) | Acme Goods | 8 Oct 2026 | Rs 332 crore (nearly $35 million) | Series C |
| Inc42 (deal table) | AcmeGoods | 8 Oct 2026 | $34.3 Mn | Series C |
| ET (headline) | acme goods | 9 Oct 2026 | Rs 332 crore | not stated |

What the round looks like after the rules:

| Field | Value | Rule that applied |
| --- | --- | --- |
| Company | Acme Goods | Two of the three reports spell it with a space. |
| Announced | 8 Oct 2026 | The earliest report. |
| Amount as reported | Rs 332 crore | Entrackr is first in the amount order and states one. |
| Amount (USD mn) | 332 x 10 / reference rate | Rupees converted at the ECB rate for 8 Oct 2026. |
| Stage | Series C | The Inc42 table names it. |
| Sources | entrackr, inc42, et | All three matched. |

The highest and lowest figures for this round are less than 1% apart, so it is not flagged. Had Inc42
printed $3.43 Mn, check C14 (a factor of ten) and check C15 (more than 10% apart) would both fire, and the
round would carry `C14 C15` in its `flags` column until someone resolved it.

## What the rules never do

- They never average two figures or split the difference.
- They never overwrite what a source said: each report keeps its own amount in
  `data/processed/reports_matched.csv`.
- They never fill a blank from memory. A city or a sector that no report states stays Unknown or
  Unclassified.

_This file is generated from `SOURCE_RULES` in `src/funding_tracker/reconcile.py`. Edit the rules there._
"""


def write_rules_doc(path: Path = ROOT / "docs" / "SOURCE_OF_TRUTH.md") -> None:
    """Write the source-of-truth rules as a document, from the same list the code and workbook use."""
    rules = pd.DataFrame(SOURCE_RULES, columns=["Field", "Rule", "Why"])
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join([RULES_INTRO, _table(rules), "", RULES_OUTRO]), encoding="utf-8")
